from paper_experiment_reproduction import RANDOM_STATE, bootstrap_mean_ci


FEATURE_SET_ORDER = [
    "gait + speech + demographics",
    "gait + speech",
    "demographics-only",
    "speech-only",
    "gait-only",
]

FEATURE_SET_LABELS = {
    "gait + speech + demographics": "Gait + speech\n+ demographics",
    "gait + speech": "Gait + speech",
    "demographics-only": "Demographics",
    "speech-only": "Speech",
    "gait-only": "Gait",
}

PAIRED_COMPARISONS = [
    ("Full vs gait + speech", "gait + speech + demographics", "gait + speech"),
    ("Full vs demographics", "gait + speech + demographics", "demographics-only"),
    ("Gait + speech vs demographics", "gait + speech", "demographics-only"),
    ("Speech vs gait", "speech-only", "gait-only"),
]

COMPARISON_LABELS = {
    "full model vs gait + speech": "Full vs gait + speech",
    "full model vs demographics-only": "Full vs demographics",
    "gait + speech vs demographics-only": "Gait + speech vs demographics",
    "speech-only vs gait-only": "Speech vs gait",
}

FEATURE_LABELS = {
    "ACC_DT": "Serial-7 accuracy",
    "Correct_Num_20s_DT": "Correct in 20 s",
    "Correct_Num_DT": "Correct count",
    "Correct_persec_DT": "Correct/sec",
    "Num_20s_DT": "Count in 20 s",
    "Num_DT": "Serial-7 count",
    "Timecount_DT_1stNum": "First response time",
    "Timecount_DT": "Dual-task time",
    "age": "Age",
    "edu": "Education",
    "gender": "Sex",
    "sex": "Sex",
    "swing_times": "Swing time",
    "average_step_assymetry": "Step asymmetry",
    "average_stride_assymetry": "Stride asymmetry",
    "stance_times": "Stance time",
    "average_stride_length": "Stride length",
    "walking_speed": "Walking speed",
    "double_support_times": "Double support",
}

PALETTE = {
    "ink": "#1E252B",
    "muted": "#66717A",
    "grid": "#DDE3E7",
    "blue": "#4C78A8",
    "teal": "#59A14F",
    "orange": "#F28E2B",
    "purple": "#8E6C8A",
    "pale_teal": "#DDEED9",
}

DOMAIN_COLORS = {
    "gait + speech + demographics": PALETTE["purple"],
    "gait + speech": PALETTE["blue"],
    "demographics-only": PALETTE["muted"],
    "speech-only": PALETTE["orange"],
    "gait-only": PALETTE["teal"],
}


def setup_style() -> None:
    mpl.rcParams.update(
        {
            "font.family": "sans-serif",
            "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans", "sans-serif"],
            "svg.fonttype": "none",
            "pdf.fonttype": 42,
            "font.size": 7,
            "axes.spines.right": False,
            "axes.spines.top": False,
            "axes.linewidth": 0.75,
            "legend.frameon": False,
            "figure.facecolor": "white",
            "axes.facecolor": "white",
        }
    )


def save_pub(fig: mpl.figure.Figure, stem: Path) -> None:
    stem.parent.mkdir(parents=True, exist_ok=True)
    for ext in ("svg", "pdf", "png", "tiff"):
        kwargs = {"bbox_inches": "tight"}
        if ext in {"png", "tiff"}:
            kwargs["dpi"] = 600
        fig.savefig(f"{stem}.{ext}", **kwargs)
    plt.close(fig)


def panel_label(ax: mpl.axes.Axes, label: str) -> None:
    ax.text(
        -0.14,
        1.08,
        label,
        transform=ax.transAxes,
        fontsize=10,
        fontweight="bold",
        va="top",
        ha="left",
        color=PALETTE["ink"],
    )


def clean_axis(ax: mpl.axes.Axes, grid_axis: str = "x") -> None:
    ax.tick_params(length=2.5, width=0.65)
    if grid_axis:
        ax.grid(axis=grid_axis, color=PALETTE["grid"], lw=0.55, alpha=0.9)
        ax.set_axisbelow(True)


def wrap_label(text: object, width: int = 18) -> str:
    return "\n".join(wrap(str(text), width=width, break_long_words=False))


def build_paired_delta_table(
    fold_metrics: pd.DataFrame,
    model: str,
    bootstrap_repeats: int,
    bootstrap_ci: float,
) -> pd.DataFrame:
    rows = []
    model_df = fold_metrics[fold_metrics["model"].eq(model)].copy()
    for comparison, feature_set_a, feature_set_b in PAIRED_COMPARISONS:
        a = model_df[model_df["feature_set"].eq(feature_set_a)][["fold", "auroc"]].rename(columns={"auroc": "auroc_a"})
        b = model_df[model_df["feature_set"].eq(feature_set_b)][["fold", "auroc"]].rename(columns={"auroc": "auroc_b"})
        merged = a.merge(b, on="fold", how="inner")
        delta = merged["auroc_a"].to_numpy(dtype=float) - merged["auroc_b"].to_numpy(dtype=float)
        lo, hi = bootstrap_mean_ci(delta, bootstrap_repeats, bootstrap_ci, RANDOM_STATE + len(rows))
        rows.append(
            {
                "comparison": comparison,
                "model": model,
                "feature_set_a": feature_set_a,
                "feature_set_b": feature_set_b,
                "mean_auroc_a": float(merged["auroc_a"].mean()),
                "mean_auroc_b": float(merged["auroc_b"].mean()),
                "mean_delta_auroc": float(delta.mean()),
                "std_delta_auroc": float(delta.std(ddof=1)),
                "ci95_low_delta_auroc": lo,
                "ci95_high_delta_auroc": hi,
                "n_paired_folds": int(len(delta)),
            }
        )
    return pd.DataFrame(rows)


def read_paired_delta(domain_results_dir: Path, model: str, bootstrap_repeats: int, bootstrap_ci: float) -> pd.DataFrame:
    paired_path = domain_results_dir / "domain_ablation_paired_delta_auroc.csv"
    if paired_path.exists():
        delta = pd.read_csv(paired_path)
        delta = delta[delta["model"].eq(model)].copy()
        if not delta.empty:
            delta["comparison"] = delta["comparison"].map(COMPARISON_LABELS).fillna(delta["comparison"])
            return delta
    fold_metrics = pd.read_csv(domain_results_dir / "domain_ablation_fold_metrics.csv")
    return build_paired_delta_table(fold_metrics, model, bootstrap_repeats, bootstrap_ci)


def create_figure(
    domain_results_dir: Path,
    paper_results_dir: Path,
    out_dir: Path,
    figure_stem: str,
    model: str,
    bootstrap_repeats: int,
    bootstrap_ci: float,
) -> None:
    performance = pd.read_csv(domain_results_dir / "domain_ablation_performance_table.csv")
    paired_delta = read_paired_delta(domain_results_dir, model, bootstrap_repeats, bootstrap_ci)
    shap = pd.read_csv(paper_results_dir / "shap_importance_Random_Forest.csv")
    recurrence = pd.read_csv(paper_results_dir / "classification/nested_feature_selection/nested_selected_feature_frequency.csv")

    out_dir.mkdir(parents=True, exist_ok=True)
    paired_delta.to_csv(out_dir / "fig4_paired_delta_auroc_source.csv", index=False)

    perf = performance[performance["model"].eq(model)].copy()
    perf["feature_set"] = pd.Categorical(perf["feature_set"], categories=FEATURE_SET_ORDER, ordered=True)
    perf_plot = perf.sort_values("feature_set").iloc[::-1].copy()

    shap_plot = shap.head(10).copy()
    shap_plot["label"] = shap_plot["Feature"].map(FEATURE_LABELS).fillna(shap_plot["Feature"])
    shap_plot = shap_plot.iloc[::-1]

    rec_plot = recurrence.head(14).copy()
    rec_plot["label"] = rec_plot["feature"].map(FEATURE_LABELS).fillna(rec_plot["feature"])
    rec_plot = rec_plot.iloc[::-1]

    fig = plt.figure(figsize=(7.25, 7.0))
    gs = GridSpec(2, 2, figure=fig, width_ratios=[1, 1], height_ratios=[1, 1], hspace=0.58, wspace=0.54)
    ax_a = fig.add_subplot(gs[0, 0])
    ax_b = fig.add_subplot(gs[0, 1])
    ax_c = fig.add_subplot(gs[1, 0])
    ax_d = fig.add_subplot(gs[1, 1])

    panel_label(ax_a, "a")
    y = np.arange(len(perf_plot))
    ax_a.hlines(y, perf_plot["ci95_low_auroc"], perf_plot["ci95_high_auroc"], color="#A6B3BB", lw=1.35, zorder=1)
    ax_a.scatter(
        perf_plot["mean_auroc"],
        y,
        s=34,
        color=[DOMAIN_COLORS[str(fs)] for fs in perf_plot["feature_set"]],
        edgecolor="white",
        linewidth=0.6,
        zorder=3,
    )
    for yi, (_, row) in enumerate(perf_plot.iterrows()):
        ax_a.text(row["mean_auroc"] + 0.006, yi, f"{row['mean_auroc']:.3f}", va="center", fontsize=6.4)
    ax_a.set_yticks(y)
    ax_a.set_yticklabels([FEATURE_SET_LABELS[str(x)] for x in perf_plot["feature_set"]], fontsize=6.4)
    ax_a.set_xlim(0.62, 0.925)
    ax_a.set_xlabel(f"{model} AUROC (95% CI)")
    ax_a.set_title("Domain ablation AUROC", loc="left", fontweight="bold", pad=6)
    clean_axis(ax_a, "x")

    panel_label(ax_b, "b")
    delta_plot = paired_delta.iloc[::-1].copy()
    y = np.arange(len(delta_plot))
    ax_b.axvline(0, color=PALETTE["ink"], lw=0.8)
    ax_b.hlines(y, delta_plot["ci95_low_delta_auroc"], delta_plot["ci95_high_delta_auroc"], color="#A6B3BB", lw=1.35)
    ax_b.scatter(delta_plot["mean_delta_auroc"], y, s=32, color=PALETTE["purple"], edgecolor="white", linewidth=0.6, zorder=3)
    for yi, (_, row) in enumerate(delta_plot.iterrows()):
        xpos = row["mean_delta_auroc"] + (0.006 if row["mean_delta_auroc"] >= 0 else -0.006)
        ha = "left" if row["mean_delta_auroc"] >= 0 else "right"
        ax_b.text(xpos, yi, f"{row['mean_delta_auroc']:+.3f}", va="center", ha=ha, fontsize=6.3)
    ax_b.set_yticks(y)
    ax_b.set_yticklabels([wrap_label(x, 21) for x in delta_plot["comparison"]], fontsize=6.2)
    ax_b.set_xlim(-0.045, 0.115)
    ax_b.set_xlabel(f"Paired Delta AUROC, {model} (95% CI)")
    ax_b.set_title("Paired Delta AUROC", loc="left", fontweight="bold", pad=6)
    clean_axis(ax_b, "x")

    panel_label(ax_c, "c")
    y = np.arange(len(shap_plot))
    ax_c.barh(y, shap_plot["avg_norm_abs_SHAP_pct"], color=PALETTE["blue"], alpha=0.92)
    ax_c.set_yticks(y)
    ax_c.set_yticklabels([wrap_label(x, 18) for x in shap_plot["label"]], fontsize=6.2)
    ax_c.set_xlabel("RF mean |SHAP| contribution (%)")
    ax_c.set_title("RF feature contribution", loc="left", fontweight="bold", pad=6)
    clean_axis(ax_c, "x")

    panel_label(ax_d, "d")
    y = np.arange(len(rec_plot))
    colors = [PALETTE["teal"] if v >= 0.8 else PALETTE["pale_teal"] for v in rec_plot["selected_fold_rate"]]
    ax_d.barh(y, rec_plot["selected_fold_rate"], color=colors, edgecolor=PALETTE["teal"], linewidth=0.65)
    ax_d.set_yticks(y)
    ax_d.set_yticklabels([wrap_label(x, 18) for x in rec_plot["label"]], fontsize=6.0)
    ax_d.set_xlim(0, 1.05)
    ax_d.xaxis.set_major_formatter(mpl.ticker.PercentFormatter(1.0))
    ax_d.set_xlabel("Selected outer folds (%)")
    ax_d.set_title("Nested feature recurrence", loc="left", fontweight="bold", pad=6)
    clean_axis(ax_d, "x")

    save_pub(fig, out_dir / figure_stem)

    pd.DataFrame(
        [
            {
                "figure": figure_stem,
                "figure_title": "Model contribution and interpretability",
                "panels": (
                    "a Domain ablation AUROC; b Paired Delta AUROC; "
                    "c RF feature contribution; d Nested feature recurrence"
                ),
                "source_tables": (
                    "domain_ablation_performance_table.csv; domain_ablation_fold_metrics.csv; "
                    "shap_importance_Random_Forest.csv; nested_selected_feature_frequency.csv"
                ),
            }
        ]
    ).to_csv(out_dir / "figure_manifest.csv", index=False)


def main() -> None:
    parser = argparse.ArgumentParser(description="Create Fig. 4 model contribution and interpretability.")
    parser.add_argument("--domain-results-dir", required=True)
    parser.add_argument("--paper-results-dir", required=True)
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--figure-stem", default="fig4_model_contribution_interpretability")
    parser.add_argument("--model", default="AdaBoost")
    parser.add_argument("--bootstrap-repeats", type=int, default=5000)
    parser.add_argument("--bootstrap-ci", type=float, default=0.95)
    args = parser.parse_args()

    setup_style()
    create_figure(
        domain_results_dir=Path(args.domain_results_dir).expanduser().resolve(),
        paper_results_dir=Path(args.paper_results_dir).expanduser().resolve(),
        out_dir=Path(args.out_dir).expanduser().resolve(),
        figure_stem=args.figure_stem,
        model=args.model,
        bootstrap_repeats=args.bootstrap_repeats,
        bootstrap_ci=args.bootstrap_ci,
    )
    print(f"Fig. 4 written to: {Path(args.out_dir).expanduser().resolve()}")


if __name__ == "__main__":
    main()
